import { describe, it, expect } from 'vitest'
import { HttpStatus2 } from '../../src/utils/http-status-2.js'
import { ContentNegotiation2 } from '../../src/utils/content-negotiation-2.js'

describe('HttpStatus2', () => {
  it('message returns correct text', () => {
    expect(HttpStatus2.message(200)).toBe('OK')
    expect(HttpStatus2.message(404)).toBe('Not Found')
    expect(HttpStatus2.message(500)).toBe('Internal Server Error')
  })

  it('message returns undefined for unknown', () => {
    expect(HttpStatus2.message(799)).toBeUndefined()
  })

  it('isInformational', () => {
    expect(HttpStatus2.isInformational(100)).toBe(true)
    expect(HttpStatus2.isInformational(200)).toBe(false)
  })

  it('isSuccessful', () => {
    expect(HttpStatus2.isSuccessful(200)).toBe(true)
    expect(HttpStatus2.isSuccessful(300)).toBe(false)
  })

  it('isRedirect', () => {
    expect(HttpStatus2.isRedirect(301)).toBe(true)
    expect(HttpStatus2.isRedirect(200)).toBe(false)
  })

  it('isClientError', () => {
    expect(HttpStatus2.isClientError(404)).toBe(true)
    expect(HttpStatus2.isClientError(500)).toBe(false)
  })

  it('isServerError', () => {
    expect(HttpStatus2.isServerError(500)).toBe(true)
    expect(HttpStatus2.isServerError(404)).toBe(false)
  })

  it('isError', () => {
    expect(HttpStatus2.isError(400)).toBe(true)
    expect(HttpStatus2.isError(200)).toBe(false)
  })

  it('register adds new code', () => {
    HttpStatus2.register(499, 'Client Closed Request')
    expect(HttpStatus2.message(499)).toBe('Client Closed Request')
  })

  it('allCodes returns array', () => {
    const codes = HttpStatus2.allCodes()
    expect(codes).toContain(200)
    expect(codes).toContain(404)
  })

  it('allMessages returns array of objects', () => {
    const msgs = HttpStatus2.allMessages()
    expect(msgs.some(m => m.code === 200 && m.message === 'OK')).toBe(true)
  })

  it('static constants', () => {
    expect(HttpStatus2.OK).toBe(200)
    expect(HttpStatus2.NOT_FOUND).toBe(404)
    expect(HttpStatus2.INTERNAL_SERVER_ERROR).toBe(500)
  })

  it('toString returns JSON', () => {
    expect(new HttpStatus2().toString()).toContain('200')
  })

  it('equals checks instance type', () => {
    expect(new HttpStatus2().equals(new HttpStatus2())).toBe(true)
    expect(new HttpStatus2().equals(null)).toBe(false)
  })
})

describe('ContentNegotiation2', () => {
  it('parseAccept parses simple header', () => {
    const result = ContentNegotiation2.parseAccept('text/html, application/json')
    expect(result).toHaveLength(2)
    expect(result[0].type).toBe('text')
    expect(result[0].subtype).toBe('html')
  })

  it('parseAccept handles q values', () => {
    const result = ContentNegotiation2.parseAccept('text/html;q=0.9, application/json;q=1.0')
    expect(result[0].q).toBe(0.9)
    expect(result[1].q).toBe(1.0)
  })

  it('parseAccept defaults q to 1.0', () => {
    const result = ContentNegotiation2.parseAccept('text/html')
    expect(result[0].q).toBe(1.0)
  })

  it('parseAccept handles wildcards', () => {
    const result = ContentNegotiation2.parseAccept('*/*')
    expect(result[0].type).toBe('*')
    expect(result[0].subtype).toBe('*')
  })

  it('bestMatch selects highest q', () => {
    const match = ContentNegotiation2.bestMatch('text/html;q=0.9, application/json;q=1.0', ['text/html', 'application/json'])
    expect(match).toBe('application/json')
  })

  it('bestMatch returns undefined for no match', () => {
    expect(ContentNegotiation2.bestMatch('text/html', ['application/json'])).toBeUndefined()
  })

  it('bestMatch handles wildcards', () => {
    expect(ContentNegotiation2.bestMatch('*/*', ['application/json'])).toBe('application/json')
  })

  it('parseLanguage parses header', () => {
    const result = ContentNegotiation2.parseLanguage('en-US, en;q=0.9')
    expect(result[0].lang).toBe('en-US')
    expect(result[1].lang).toBe('en')
    expect(result[1].q).toBe(0.9)
  })

  it('bestLanguage selects best match', () => {
    const match = ContentNegotiation2.bestLanguage('en;q=0.9, fr;q=1.0', ['en', 'fr'])
    expect(match).toBe('fr')
  })

  it('parseEncoding parses header', () => {
    const result = ContentNegotiation2.parseEncoding('gzip, deflate;q=0.8')
    expect(result[0].encoding).toBe('gzip')
    expect(result[1].encoding).toBe('deflate')
  })

  it('matches type and subtype', () => {
    expect(ContentNegotiation2.matches('text/*', 'text/html')).toBe(true)
    expect(ContentNegotiation2.matches('*/*', 'application/json')).toBe(true)
    expect(ContentNegotiation2.matches('text/html', 'application/json')).toBe(false)
  })

  it('equals checks instance type', () => {
    expect(new ContentNegotiation2().equals(new ContentNegotiation2())).toBe(true)
    expect(new ContentNegotiation2().equals(null)).toBe(false)
  })
})

