import { describe, it, expect } from 'vitest'
import { SessionStore2 } from '../../src/utils/session-store-2.js'
import { IdentityProviderManager2 } from '../../src/utils/identity-provider-2.js'

describe('SessionStore2', () => {
  it('create adds session', () => {
    const ss = new SessionStore2()
    const id = ss.create('user1', '127.0.0.1', 'Mozilla')
    expect(ss.get(id)).toBeDefined()
    expect(ss.get(id)?.state).toBe('active')
  })

  it('create enforces max sessions', () => {
    const ss = new SessionStore2().setPolicy({ maxSessions: 2, sessionTimeout: 86400000, idleTimeout: 1800000, refreshThreshold: 3600000, revokeOnPasswordChange: true })
    const id1 = ss.create('user1', '127.0.0.1', 'UA')
    ss.create('user1', '127.0.0.1', 'UA')
    ss.create('user1', '127.0.0.1', 'UA')
    expect(ss.getUserSessions('user1').filter(s => s.state === 'active').length).toBeLessThanOrEqual(2)
  })

  it('setToken and getToken', () => {
    const ss = new SessionStore2()
    const id = ss.create('user1', '127.0.0.1', 'UA')
    ss.setToken(id, 'access', 'token123', Date.now() + 3600000)
    expect(ss.getToken(id, 'access')).toBe('token123')
  })

  it('getToken returns null for expired token', () => {
    const ss = new SessionStore2()
    const id = ss.create('user1', '127.0.0.1', 'UA')
    ss.setToken(id, 'access', 'token123', Date.now() - 1000)
    expect(ss.getToken(id, 'access')).toBeNull()
  })

  it('revokeToken invalidates token', () => {
    const ss = new SessionStore2()
    const id = ss.create('user1', '127.0.0.1', 'UA')
    ss.setToken(id, 'refresh', 'rt', Date.now() + 86400000)
    ss.revokeToken(id, 'refresh')
    expect(ss.getToken(id, 'refresh')).toBeNull()
  })

  it('touch updates lastAccessedAt', () => {
    const ss = new SessionStore2()
    const id = ss.create('user1', '127.0.0.1', 'UA')
    const old = ss.get(id)!.lastAccessedAt
    ss.touch(id)
    expect(ss.get(id)!.lastAccessedAt).toBeGreaterThanOrEqual(old)
  })

  it('refresh extends expiry when near threshold', () => {
    const ss = new SessionStore2().setPolicy({ maxSessions: 5, sessionTimeout: 100, idleTimeout: 1800000, refreshThreshold: 3600000, revokeOnPasswordChange: true })
    const id = ss.create('user1', '127.0.0.1', 'UA')
    expect(ss.refresh(id)).toBe(true)
  })

  it('revoke marks session revoked', () => {
    const ss = new SessionStore2()
    const id = ss.create('user1', '127.0.0.1', 'UA')
    ss.revoke(id, 'logout')
    expect(ss.get(id)?.state).toBe('revoked')
  })

  it('revokeAllForUser revokes all', () => {
    const ss = new SessionStore2()
    ss.create('user1', '127.0.0.1', 'UA')
    ss.create('user1', '127.0.0.1', 'UA')
    const count = ss.revokeAllForUser('user1')
    expect(count).toBe(2)
  })

  it('revokeIdle marks idle sessions', () => {
    const ss = new SessionStore2().setPolicy({ maxSessions: 5, sessionTimeout: 86400000, idleTimeout: 0, refreshThreshold: 3600000, revokeOnPasswordChange: true })
    ss.create('user1', '127.0.0.1', 'UA')
    const count = ss.revokeIdle()
    expect(count).toBeGreaterThan(0)
  })

  it('sweepExpired marks expired sessions', () => {
    const ss = new SessionStore2().setPolicy({ maxSessions: 5, sessionTimeout: 0, idleTimeout: 1800000, refreshThreshold: 3600000, revokeOnPasswordChange: true })
    ss.create('user1', '127.0.0.1', 'UA')
    const count = ss.sweepExpired()
    expect(count).toBeGreaterThan(0)
  })

  it('getUserSessions returns user sessions', () => {
    const ss = new SessionStore2()
    ss.create('user1', '127.0.0.1', 'UA')
    ss.create('user1', '127.0.0.1', 'UA')
    ss.create('user2', '127.0.0.1', 'UA')
    expect(ss.getUserSessions('user1')).toHaveLength(2)
  })

  it('isValid checks active and not expired', () => {
    const ss = new SessionStore2()
    const id = ss.create('user1', '127.0.0.1', 'UA')
    expect(ss.isValid(id)).toBe(true)
    ss.revoke(id)
    expect(ss.isValid(id)).toBe(false)
  })

  it('setMetadata adds metadata', () => {
    const ss = new SessionStore2()
    const id = ss.create('user1', '127.0.0.1', 'UA')
    ss.setMetadata(id, 'device', 'mobile')
    expect(ss.get(id)?.metadata['device']).toBe('mobile')
  })

  it('listen receives events', () => {
    const ss = new SessionStore2()
    let events: string[] = []
    ss.listen((e) => events.push(e))
    ss.create('user1', '127.0.0.1', 'UA')
    expect(events).toContain('session-created')
  })

  it('getStats returns counts', () => {
    const ss = new SessionStore2()
    ss.create('user1', '127.0.0.1', 'UA')
    expect(ss.getStats().total).toBe(1)
  })

  it('count returns size', () => {
    const ss = new SessionStore2()
    ss.create('user1', '127.0.0.1', 'UA')
    expect(ss.count()).toBe(1)
  })

  it('clear resets', () => {
    const ss = new SessionStore2()
    ss.create('user1', '127.0.0.1', 'UA')
    ss.clear()
    expect(ss.count()).toBe(0)
  })

  it('equals compares', () => {
    const a = new SessionStore2()
    const b = new SessionStore2()
    expect(a.equals(b)).toBe(true)
    expect(a.equals(null)).toBe(false)
  })
})

describe('IdentityProviderManager2', () => {
  it('addProvider registers provider', () => {
    const im = new IdentityProviderManager2()
    const id = im.addProvider('google', 'oidc')
    expect(im.getProvider(id)).toBeDefined()
  })

  it('removeProvider deletes provider', () => {
    const im = new IdentityProviderManager2()
    const id = im.addProvider('google', 'oidc')
    im.removeProvider(id)
    expect(im.getProvider(id)).toBeUndefined()
  })

  it('enableProvider and disableProvider', () => {
    const im = new IdentityProviderManager2()
    const id = im.addProvider('google', 'oidc')
    im.disableProvider(id)
    expect(im.getProvider(id)?.enabled).toBe(false)
    im.enableProvider(id)
    expect(im.getProvider(id)?.enabled).toBe(true)
  })

  it('linkIdentity creates identity', () => {
    const im = new IdentityProviderManager2()
    const pid = im.addProvider('google', 'oidc')
    const iid = im.linkIdentity(pid, 'ext123', 'user@example.com', 'User')
    expect(iid).not.toBeNull()
    expect(im.getIdentity(iid!)).toBeDefined()
  })

  it('linkIdentity fails for disabled provider', () => {
    const im = new IdentityProviderManager2()
    const pid = im.addProvider('google', 'oidc')
    im.disableProvider(pid)
    expect(im.linkIdentity(pid, 'ext123')).toBeNull()
  })

  it('unlinkIdentity removes identity', () => {
    const im = new IdentityProviderManager2()
    const pid = im.addProvider('google', 'oidc')
    const iid = im.linkIdentity(pid, 'ext123', 'u@e.com')
    im.unlinkIdentity(iid!)
    expect(im.getIdentity(iid!)).toBeUndefined()
  })

  it('addGroup adds group', () => {
    const im = new IdentityProviderManager2()
    const pid = im.addProvider('google', 'oidc')
    const iid = im.linkIdentity(pid, 'ext123')
    im.addGroup(iid!, 'admins')
    expect(im.getIdentity(iid!)?.groups).toContain('admins')
  })

  it('createRole adds role', () => {
    const im = new IdentityProviderManager2()
    const id = im.createRole('admin', [{ resource: '*', action: '*', effect: 'allow', conditions: {} }])
    expect(im.getRole(id)).toBeDefined()
  })

  it('addPermission adds permission', () => {
    const im = new IdentityProviderManager2()
    const id = im.createRole('user')
    im.addPermission(id, { resource: 'docs', action: 'read', effect: 'allow', conditions: {} })
    expect(im.getRole(id)?.permissions).toHaveLength(1)
  })

  it('assignRole and revokeRole', () => {
    const im = new IdentityProviderManager2()
    const rid = im.createRole('user')
    im.assignRole('user1', rid)
    expect(im.getUserRoles('user1')).toHaveLength(1)
    im.revokeRole('user1', rid)
    expect(im.getUserRoles('user1')).toHaveLength(0)
  })

  it('hasPermission checks permissions', () => {
    const im = new IdentityProviderManager2()
    const rid = im.createRole('editor', [
      { resource: 'docs', action: 'read', effect: 'allow', conditions: {} },
      { resource: 'docs', action: 'write', effect: 'allow', conditions: {} },
    ])
    im.assignRole('user1', rid)
    expect(im.hasPermission('user1', 'docs', 'read')).toBe(true)
    expect(im.hasPermission('user1', 'docs', 'delete')).toBe(false)
  })

  it('getAllPermissions includes parent role', () => {
    const im = new IdentityProviderManager2()
    const parentId = im.createRole('base', [{ resource: 'docs', action: 'read', effect: 'allow', conditions: {} }])
    const childId = im.createRole('extended', [{ resource: 'docs', action: 'write', effect: 'allow', conditions: {} }], parentId)
    im.assignRole('user1', childId)
    const perms = im.getAllPermissions('user1')
    expect(perms).toHaveLength(2)
  })

  it('getProviderByDomain finds provider', () => {
    const im = new IdentityProviderManager2()
    im.addProvider('google', 'oidc', {}, ['example.com', 'test.com'])
    expect(im.getProviderByDomain('example.com')).toBeDefined()
  })

  it('getIdentitiesByProvider filters', () => {
    const im = new IdentityProviderManager2()
    const pid1 = im.addProvider('google', 'oidc')
    const pid2 = im.addProvider('github', 'oauth2')
    im.linkIdentity(pid1, 'ext1')
    im.linkIdentity(pid2, 'ext2')
    expect(im.getIdentitiesByProvider(pid1)).toHaveLength(1)
  })

  it('touchIdentity updates lastSeenAt', () => {
    const im = new IdentityProviderManager2()
    const pid = im.addProvider('google', 'oidc')
    const iid = im.linkIdentity(pid, 'ext1')
    const old = im.getIdentity(iid!)!.lastSeenAt
    im.touchIdentity(iid!)
    expect(im.getIdentity(iid!)!.lastSeenAt).toBeGreaterThanOrEqual(old)
  })

  it('listen receives events', () => {
    const im = new IdentityProviderManager2()
    let events: string[] = []
    im.listen((e) => events.push(e))
    im.addProvider('google', 'oidc')
    expect(events).toContain('provider-added')
  })

  it('getStats returns counts', () => {
    const im = new IdentityProviderManager2()
    im.addProvider('google', 'oidc')
    im.createRole('user')
    expect(im.getStats().providers).toBe(1)
    expect(im.getStats().roles).toBe(1)
  })

  it('count returns identities', () => {
    const im = new IdentityProviderManager2()
    expect(im.count()).toBe(0)
  })

  it('clear resets', () => {
    const im = new IdentityProviderManager2()
    im.addProvider('google', 'oidc')
    im.clear()
    expect(im.count()).toBe(0)
  })

  it('equals compares', () => {
    const a = new IdentityProviderManager2()
    const b = new IdentityProviderManager2()
    expect(a.equals(b)).toBe(true)
    expect(a.equals(null)).toBe(false)
  })
})


