import { Args, Command, Flags } from '@oclif/core'
import { existsSync } from 'node:fs'
import * as fs from 'node:fs/promises'
import { extname, resolve } from 'node:path'
import ora from 'ora'

import { discoverFiles } from '../core/file-discovery.js'
import {
  buildAnatomyResult,
  type AnatomyOptions,
  type AnatomyResult,
} from './anatomy-helpers.js'
import { formatAnatomyJson, formatAnatomyTable } from './anatomy-format-helpers.js'

export default class Anatomy extends Command {
  static override args = {
    path: Args.string({
      default: '.',
      description: 'Path to analyze',
      required: false,
    }),
  }

  static override description = 'Perform an anatomical analysis of the codebase'

  static override examples = [
    {
      command: '<%= config.bin %> anatomy',
      description: 'Analyze codebase anatomy',
    },
    {
      command: '<%= config.bin %> anatomy ./src --format json',
      description: 'Anatomy as JSON',
    },
    {
      command: '<%= config.bin %> anatomy --verbose',
      description: 'Detailed analysis',
    },
  ]

  static override flags = {
    ext: Flags.string({
      default: '',
      description: 'Comma-separated file extensions to analyze (e.g., ".ts,.tsx")',
    }),
    format: Flags.string({
      char: 'f',
      default: 'table',
      description: 'Output format',
      options: ['json', 'table'],
    }),
    ignore: Flags.string({
      char: 'i',
      description: 'Patterns to ignore',
      multiple: true,
    }),
    output: Flags.string({
      char: 'o',
      description: 'Output file path',
    }),
    verbose: Flags.boolean({
      char: 'v',
      default: false,
      description: 'Show detailed output',
    }),
  }

  async run(): Promise<void> {
    const { args, flags } = await this.parse(Anatomy)

    const targetPath = resolve(args.path as string)

    if (!existsSync(targetPath)) {
      this.error(`Path not found: ${targetPath}`, { exit: 1 })
    }

    const format = flags.format as 'json' | 'table'
    const options: AnatomyOptions = { verbose: flags.verbose }

    const spinner = ora('Preparing anatomical examination...').start()

    const defaultIgnore = ['**/node_modules/**', '**/dist/**', '**/coverage/**', '**/.git/**']
    const ignore = flags.ignore ? [...defaultIgnore, ...flags.ignore] : defaultIgnore

    const discoveredFiles = await discoverFiles({
      cwd: targetPath,
      ignore,
      patterns: ['**/*.ts', '**/*.tsx', '**/*.js', '**/*.jsx'],
    })

    const extensions = flags.ext
      ? flags.ext
          .split(',')
          .map((e) => e.trim())
          .filter(Boolean)
      : null

    const filteredFiles = extensions
      ? discoveredFiles.filter((f) => {
          const ext = extname(f.path).toLowerCase()
          return extensions.includes(ext)
        })
      : discoveredFiles

    spinner.text = 'Examining body systems...'

    const contents: string[] = await Promise.all(
      filteredFiles.map(async (file) => {
        try {
          return await fs.readFile(file.absolutePath, 'utf8')
        } catch {
          return ''
        }
      }),
    )

    const files = filteredFiles.map((f) => f.path)

    const result: AnatomyResult = buildAnatomyResult(files, contents, options)

    spinner.succeed(`Examination complete: overall health ${result.stats.overallHealth}%`)

    const outputData = format === 'json' ? formatAnatomyJson(result) : formatAnatomyTable(result)

    if (flags.output) {
      try {
        await fs.writeFile(flags.output, outputData, 'utf8')
        this.log(`Results written to ${flags.output}`)
      } catch (error) {
        this.error(
          `Failed to write output to ${flags.output}: ${error instanceof Error ? error.message : String(error)}`,
        )
      }
    } else {
      this.log(outputData)
    }
  }
}

export { buildAnatomyResult } from './anatomy-helpers.js'
export type { AnatomyResult, AnatomyStats, BodySystem, Organ, VitalSigns } from './anatomy-helpers.js'
export { formatAnatomyJson, formatAnatomyTable } from './anatomy-format-helpers.js'
